/**
 * Issue #283 — Cloudflare CDN cache purge webhook.
 *
 * This endpoint is called automatically on major version deployments (from CI)
 * to purge Cloudflare's edge cache for static assets and market metadata API
 * responses, ensuring users receive fresh content immediately after a release.
 *
 * Required environment variables (server-side only, never NEXT_PUBLIC_):
 *   CLOUDFLARE_ZONE_ID     — the Cloudflare Zone ID for the iPredict domain
 *   CLOUDFLARE_API_TOKEN   — a Cloudflare API token with Cache Purge permission
 *   CACHE_PURGE_SECRET     — shared secret that the CI pipeline must supply in
 *                            the Authorization header to prevent unauthorized purges
 *
 * Request:
 *   POST /api/cache-purge
 *   Authorization: Bearer <CACHE_PURGE_SECRET>
 *   Content-Type: application/json
 *   Body (optional): { "urls": ["https://..."] }
 *     — if `urls` is omitted, the entire zone cache is purged (purge_everything).
 *     — if `urls` is provided, only those specific URLs are purged.
 *
 * Response:
 *   200 { "purged": true, "result": <Cloudflare API result> }
 *   401 if the Authorization header is missing or invalid
 *   500 if the Cloudflare API call fails
 *
 * CI Integration example (GitHub Actions):
 *   - name: Purge Cloudflare cache
 *     run: |
 *       curl -X POST https://ipredict.app/api/cache-purge \
 *         -H "Authorization: Bearer ${{ secrets.CACHE_PURGE_SECRET }}" \
 *         -H "Content-Type: application/json" \
 *         -d '{"urls":[]}'
 */

import { NextRequest, NextResponse } from "next/server";

export const runtime = "edge";

/** URLs purged on every deployment (static assets regenerated by the build). */
const DEFAULT_PURGE_URLS = [
  // Market list API responses cached at the edge
  "https://ipredict.app/api/markets",
  // Public homepage (may reference old JS bundle hashes via HTML)
  "https://ipredict.app/",
  "https://www.ipredict.app/",
];

export async function POST(req: NextRequest): Promise<NextResponse> {
  // ── Authorization ──────────────────────────────────────────────────────────
  const purgeSecret = process.env.CACHE_PURGE_SECRET;
  if (!purgeSecret) {
    return NextResponse.json(
      { error: "Cache purge endpoint is not configured (CACHE_PURGE_SECRET missing)" },
      { status: 503 }
    );
  }

  const authHeader = req.headers.get("authorization") ?? "";
  const token = authHeader.startsWith("Bearer ") ? authHeader.slice(7) : "";
  if (!token || token !== purgeSecret) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  // ── Cloudflare credentials ─────────────────────────────────────────────────
  const zoneId = process.env.CLOUDFLARE_ZONE_ID;
  const apiToken = process.env.CLOUDFLARE_API_TOKEN;
  if (!zoneId || !apiToken) {
    return NextResponse.json(
      { error: "Cloudflare credentials not configured" },
      { status: 503 }
    );
  }

  // ── Parse request body ─────────────────────────────────────────────────────
  let body: { urls?: string[] } = {};
  try {
    const text = await req.text();
    if (text) body = JSON.parse(text);
  } catch {
    // malformed JSON — treat as purge-all
  }

  const urlsToPurge: string[] | undefined = Array.isArray(body.urls) && body.urls.length > 0
    ? body.urls
    : undefined;

  // ── Call Cloudflare Cache Purge API ────────────────────────────────────────
  // Docs: https://developers.cloudflare.com/api/operations/zone-purge
  const cfEndpoint = `https://api.cloudflare.com/client/v4/zones/${zoneId}/purge_cache`;

  const cfPayload = urlsToPurge
    ? { files: urlsToPurge }                     // selective URL purge
    : { files: DEFAULT_PURGE_URLS };             // deployment default set

  let cfResponse: Response;
  try {
    cfResponse = await fetch(cfEndpoint, {
      method: "POST",
      headers: {
        "Authorization": `Bearer ${apiToken}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify(cfPayload),
    });
  } catch (err) {
    return NextResponse.json(
      { error: "Failed to reach Cloudflare API", detail: String(err) },
      { status: 502 }
    );
  }

  const cfResult = await cfResponse.json();

  if (!cfResponse.ok || !cfResult.success) {
    return NextResponse.json(
      { error: "Cloudflare cache purge failed", cloudflare: cfResult },
      { status: 502 }
    );
  }

  return NextResponse.json({
    purged: true,
    urls: urlsToPurge ?? DEFAULT_PURGE_URLS,
    result: cfResult.result,
  });
}

// Block other HTTP methods
export async function GET(): Promise<NextResponse> {
  return NextResponse.json({ error: "Use POST" }, { status: 405 });
}
